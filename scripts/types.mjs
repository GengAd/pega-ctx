// Writes src/mcp/types.mjs from the Pega plugin's JSON Schemas: one entry per rule class that
// create-rule accepts, with its short type name and the field its name comes from.
// Run again when the Pega plugin changes version: node scripts/types.mjs
import { writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { readSchemas, skillsFolder, keyOf } from '../src/mcp/schemas.mjs';
import { shortName } from '../src/mcp/names.mjs';

const folder = skillsFolder();
const rows = readSchemas(folder).map(({ ruleClass, skill, file, schema }) => ({
  type: shortName(ruleClass),
  ruleClass,
  key: keyOf(schema),
  skill,
  schema: file,
}));
const out = join(import.meta.dirname, '../src/mcp/types.mjs');
const lines = [
  '// Generated by scripts/types.mjs from the Pega plugin\'s JSON Schemas: do not edit by hand.',
  `// Source: ${folder.split('/').slice(-2).join('/')} (${rows.length} rule classes, the ones create-rule accepts).`,
  '// key: the field(s) the rule\'s name comes from; several are joined by a space in the name.',
  'export const WRITABLE = [',
  ...rows.map((r) => `  ${JSON.stringify(r)},`),
  '];',
  '',
];
writeFileSync(out, lines.join('\n'));
console.log(`${out}: ${rows.length} rule classes`);
